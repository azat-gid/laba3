import math

def calculate_function(x):
    """
    Вычисляет значение y для графика №3.
    """
    if x < -9 or x > 5:
        return None, "Вне графика"

    # Участок 1: Дуга окружности (спуск и подъем)
    # Центр: (-7, 2), Радиус R = 2. Уравнение: y = 2 - sqrt(4 - (x+7)^2)
    elif -9 <= x <= -5:
        y = 2 - math.sqrt(4 - (x + 7) ** 2)
        part = "Дуга окружности"

    # Участок 2: Горизонтальная прямая
    elif -5 < x <= -4:
        y = 2.0
        part = "Горизонтальная прямая"

    # Участок 3: Наклонная прямая (от (-4, 2) до (0, 0))
    elif -4 < x <= 0:
        y = -0.5 * x
        part = "Наклонная прямая"

    # Участок 4: Синусоида (от 0 до pi)
    elif 0 < x <= math.pi:
        y = math.sin(x)
        part = "Синусоида"

    # Участок 5: Прямая под 45 градусов (от pi до 5)
    elif math.pi < x <= 5:
        y = x - math.pi
        part = "Прямая 45°"

    return y, part


def main():
    # 1. Задаем параметры интервала и шага
    x_start = -9.0
    x_end = 5.0
    dx = 0.5  # Шаг таблицы (можно изменить на 0.25 или 0.1 для большей точности)

    # 2. Выводим заголовок таблицы
    print("=" * 75)
    print("ЛАБОРАТОРНАЯ РАБОТА №3 «ОРГАНИЗАЦИЯ ЦИКЛОВ». ЗАДАНИЕ 1")
    print("График №3. Таблица значений функции")
    print("=" * 75)
    
    # Шапка таблицы
    print(f"{'X':<10} | {'Y':<15} | {'Участок графика':<30}")
    print("-" * 75)

    # 3. Организуем цикл (используем while, как чаще всего требуют)
    x = x_start
    # Добавляем 0.0001, чтобы из-за погрешности float цикл не остановился раньше времени
    while x <= x_end + 0.0001: 
        y, part = calculate_function(x)
        
        # Выводим строку таблицы с выравниванием
        if y is not None:
            # :.2f - два знака после запятой для X, :.4f - четыре для Y
            print(f"{x:<10.2f} | {y:<15.4f} | {part:<30}")
            
        x += dx  # Увеличиваем X на шаг dx

    print("=" * 75)

if __name__ == "__main__":
    main()
