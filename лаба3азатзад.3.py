import math


def main():
    print("=" * 85)
    print("ЗАДАНИЕ 3. Вычисление функции e^x с помощью ряда Тейлора")
    print("=" * 85)

    # --- Ввод данных ---
    try:
        x_start = float(input("Введите Xнач (например, -2): "))
        x_end = float(input("Введите Xкон (например, 2): "))
        dx = float(input("Введите шаг dx (например, 0.5): "))
        eps = float(input("Введите точность eps (например, 0.0001): "))
    except ValueError:
        print("Ошибка ввода! Пожалуйста, вводите числа (дробная часть через точку).")
        return

    print("\n" + "-" * 85)
    print(f"| {'X':^7} | {'Ряд Тейлора':^16} | {'Точное значение':^16} | {'Погрешность':^12} | {'N':^4} |")
    print("-" * 85)

    x = x_start
    while x <= x_end + dx / 1000:

        n = 0
        current_term = 1.0  # Первый член ряда (n=0), равен 1
        sum_y = 0.0

        # --- Вычисление суммы ряда ---
        while abs(current_term) > eps:
            sum_y += current_term
            n += 1
            # Рекуррентная формула для e^x: следующий член = текущий * (x / n)
            # Обратите внимание: здесь БЕЗ минуса!
            current_term *= x / n

        # --- Проверка (точное значение) ---
        true_y = math.exp(x)

        # Вычисляем абсолютную разницу
        error = abs(true_y - sum_y)

        # Вывод строки таблицы
        print(f"| {x:7.2f} | {sum_y:16.6f} | {true_y:16.6f} | {error:12.2e} | {n:4d} |")

        x += dx

    print("-" * 85)
    print("Примечание: 'Погрешность' — это разница между суммой ряда и точным значением функции.")
    print("Она должна быть очень маленькой (близкой к нулю), что подтверждает правильность работы.")


if __name__ == "__main__":
    main()